export type Translations = typeof T.ru;
type DeepKeyOf<T> = T extends object
  ? { [K in keyof T]: K extends string ? `${K}` | `${K}.${DeepKeyOf<T[K]>}` : never }[keyof T]
  : never;

type PathValue<T, P extends string> =
  P extends `${infer K}.${infer Rest}`
  ? K extends keyof T ? PathValue<T[K], Rest> : never
  : P extends keyof T ? T[P] : never;

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: <P extends DeepKeyOf<Translations>>(path: P) => PathValue<Translations, P>;
}

const LangContext = createContext<LangCtx>({} as LangCtx);

function getPath(obj: any, path: string): any {
  return path.split(".").reduce((acc, k) => acc?.[k], obj);
}

// Активный язык для не-хукового доступа: модульные функции (форматирование
// дат, подписи медиа) не могут вызывать useLang — читают отсюда. Значение
// синхронизирует LanguageProvider.
let activeLang: Lang = "ru";
export function getActiveLang(): Lang { return activeLang; }
export function tr(path: string): string {
  return (getPath(T[activeLang], path) ?? getPath(T.ru, path) ?? path) as string;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ru");

  useEffect(() => {
    const saved = localStorage.getItem("lang") as Lang | null;
    if (saved && (saved === "ru" || saved === "uz" || saved === "tg")) { activeLang = saved; setLangState(saved); }
    // Разовая синхронизация на старте: у веб-игроков в БД мог остаться язык
    // по умолчанию — сервер должен знать реальный язык интерфейса.
    syncLang(saved && ["ru", "uz", "tg"].includes(saved) ? saved : "ru");
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const syncLang = useCallback((l: Lang) => {
    // Серверные уведомления приходят на языке игрока — синхронизируем выбор.
    try {
      const token = localStorage.getItem("efootball_jwt");
      if (!token) return;
      void fetch("/api/me/lang", {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
        body: JSON.stringify({ lang: l }),
      });
    } catch { /* оффлайн — синхронизируем в следующий раз */ }
  }, []);

  const setLang = useCallback((l: Lang) => {
    activeLang = l;
    setLangState(l);
    localStorage.setItem("lang", l);
    syncLang(l);
  }, [syncLang]);

  const t = useCallback(
    (path: string) => getPath(T[lang], path) ?? getPath(T.ru, path) ?? path,
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t: t as any }), [lang, setLang, t]);

  return (
    <LangContext.Provider value={value}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}

